#!/usr/bin/env bash
# Regenerate the pinned backend lock files from the *.in files.
# Usage: ./scripts/lock-deps.sh
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT/backend"

TMPVENV="$(mktemp -d)/venv"
python3 -m venv "$TMPVENV"
# shellcheck disable=SC1091
source "$TMPVENV/bin/activate"
pip install --quiet --upgrade pip

pip install --quiet -r requirements.in
{
  echo "# Generated by scripts/lock-deps.sh from requirements.in -- do not edit by hand."
  pip freeze --exclude-editable
} > requirements.lock.txt

pip install --quiet -r requirements-dev.in
{
  echo "# Generated by scripts/lock-deps.sh from requirements-dev.in -- do not edit by hand."
  pip freeze --exclude-editable
} > requirements-dev.lock.txt

deactivate
echo "Wrote backend/requirements.lock.txt and backend/requirements-dev.lock.txt"
